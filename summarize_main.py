"""
Summary table of the main analysis (run_comparisons.py --plan main), after merge_results.py:

    python summarize_main.py --results results/all [--latex paper/tables/main_results.tex]

Prints, for every feature set and temporal context, the mean reconstruction correlation over participants
(mean over folds and Mel bins per participant), its SD over participants, the per-participant values, the
chance level (randomResults: correlation of the spectrogram with a copy split at a random point and swapped, as in Verwoert et al.) and the n_comp values chosen by the
nested cross-validation. With --latex, writes the body of the results table used in the paper.
"""
import argparse
import os

import numpy as np

# (row label, SET, context) in table order; context 'past' = past-only (-400..0 ms), 'sym' = +-200 ms
ROWS = [
    ('Causal bandpass (buffered)', None, None),
    ('HG', 'HG_buf', 'past'),
    ('HG + LP amplitude', 'HG_LPamp_buf', 'past'),
    ('HG + LP (amplitude + phase)', 'HG_LP_buf', 'past'),
    ('HG + LP + PAC', 'HG_LP_PAC_buf', 'past'),
    ('HG + LP + phase-resolved PAC', 'HG_LP_PACc_buf', 'past'),
    ('HG + LP amplitude + LMP (post hoc)', 'HG_LPamp_LMP_buf', 'past'),
    ('Matched bandpass (buffered)', None, None),
    ('Amplitude', 'BPm_amp_buf', 'past'),
    ('Amplitude + phase', 'BPm_phase_buf', 'past'),
    ('Amplitude + phase + PAC', 'BPm_pac_buf', 'past'),
    ('SSR (causal)', None, None),
    ('Amplitude', 'SSR_amp', 'past'),
    ('Amplitude + phase', 'SSR_phase', 'past'),
    ('Amplitude + phase + PAC', 'SSR_pac', 'past'),
    ('Amplitude + phase + phase-resolved PAC', 'SSR_pacc', 'past'),
    ('Offline bandpass (Verwoert et al.)', None, None),
    ('HG', 'HG_vw', 'past'),
    ('HG + LP (amplitude + phase)', 'HG_LP_vw', 'past'),
    ('HG + LP + PAC', 'HG_LP_PAC_vw', 'past'),
]
SYM = {'HG_vw', 'HG_LP_vw', 'HG_LP_PAC_vw', 'SSR_amp', 'SSR_phase', 'SSR_pac'}


def prefix(name, ctx):
    return f"cmp_{name}{'_causal' if ctx == 'past' else ''}_nested"


def load(results, name, ctx, kind='linearResults'):
    f = os.path.join(results, f'{prefix(name, ctx)}{kind}.npy')
    return np.load(f) if os.path.exists(f) else None


def per_participant(arr):
    return np.asarray(arr, float).reshape(arr.shape[0], -1).mean(axis=1)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--results', default='results/all')
    ap.add_argument('--latex', default=None)
    args = ap.parse_args()

    lines = []
    print(f"{'feature set':42s} {'past-only':>15s} {'+-200 ms':>15s}   chance   n_comp (past)   per participant (past)")
    for label, name, ctx in ROWS:
        if name is None:
            print(f'\n{label}')
            lines.append(f'\\multicolumn{{4}}{{l}}{{\\textit{{{label}}}}} \\\\')
            continue
        cells, cells_tex = [], []
        for c in ('past', 'sym'):
            a = load(args.results, name, c) if (c == 'past' or name in SYM) else None
            if a is None:
                cells.append('-'); cells_tex.append('--')
            else:
                pp = per_participant(a)
                sd = pp.std(ddof=1) if len(pp) > 1 else 0.0
                cells.append(f'{pp.mean():.3f} +- {sd:.3f}')
                cells_tex.append(f'${pp.mean():.3f} \\pm {sd:.3f}$')
        a = load(args.results, name, 'past')
        rnd = load(args.results, name, 'past', 'randomResults')
        if rnd is None and os.path.exists(os.path.join(args.results, 'chance_null.npz')):
            # compact copy kept in the repository: null correlations averaged over Mel bins, (participants, 1000)
            null = np.load(os.path.join(args.results, 'chance_null.npz'))
            rnd = null[prefix(name, 'past')] if prefix(name, 'past') in null.files else None
        nc = load(args.results, name, 'past', 'nComp')
        chance = f'{per_participant(rnd).mean():.3f}' if rnd is not None else '-'
        ncs = (f'{int(np.median(nc))} [{int(np.min(nc))}-{int(np.max(nc))}]' if nc is not None else '-')
        pps = ' '.join(f'{x:.3f}' for x in per_participant(a)) if a is not None else ''
        print(f'  {label:40s} {cells[0]:>15s} {cells[1]:>15s}   {chance:>6s}   {ncs:>13s}   {pps}')
        nc_tex = f'{np.median(nc):g}' if nc is not None else '--'
        lines.append(f'\\quad {label} & {cells_tex[0]} & {cells_tex[1]} & {nc_tex} \\\\')
    if args.latex:
        os.makedirs(os.path.dirname(args.latex) or '.', exist_ok=True)
        with open(args.latex, 'w') as f:
            f.write('% generated by summarize_main.py\n\\begin{tabular}{lccc}\n\\toprule\n'
                    '\\textbf{Feature set} & \\textbf{Past-only} & \\textbf{$\\pm200$\\,ms} & \\textbf{PLS comp.} \\\\\n'
                    '\\midrule\n' + '\n'.join(lines) + '\n\\bottomrule\n\\end{tabular}\n')
        print(f'\nwrote {args.latex}')


if __name__ == '__main__':
    main()
